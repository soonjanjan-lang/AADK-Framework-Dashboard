  function binData(xs, ys, mask, W, b) {
    var acc = {};
    for (var i = 0; i < xs.length; i++) {
      if (mask && !mask(i)) continue;
      var x = xs[i], y = ys[i];
      if (y == null || x < -W || x >= W) continue;
      var mid = Math.floor(x / b) * b + b / 2;
      var a = acc[mid] || (acc[mid] = { mid: mid, n: 0, s: 0, ss: 0, from: Math.floor(x / b) * b });
      a.n++; a.s += y; a.ss += y * y;
    }
    return Object.keys(acc).map(function (k) {
      var a = acc[k], m = a.s / a.n, v = a.n > 1 ? (a.ss - a.n * m * m) / (a.n - 1) : 0;
      return { mid: a.mid, from: a.from, to: a.from + b, n: a.n, mean: m, se: Math.sqrt(Math.max(v, 0) / a.n) };
    }).sort(function (p, q) { return p.mid - q.mid; });
  }
  function wfit(pts) {             // straight line through the dots, each weighted by its count
    var sw = 0, sx = 0, sy = 0, sxx = 0, sxy = 0;
    pts.forEach(function (p) { sw += p.n; sx += p.n * p.mid; sy += p.n * p.mean; sxx += p.n * p.mid * p.mid; sxy += p.n * p.mid * p.mean; });
    var den = sw * sxx - sx * sx;
    var slope = den ? (sw * sxy - sx * sy) / den : 0;
    return { a: (sy - slope * sx) / sw, b: slope };
  }
  function rdFit(xs, ys, mask, W, b) {
    var bins = binData(xs, ys, mask, W, b);
    var L = bins.filter(function (p) { return p.mid < 0; }), R = bins.filter(function (p) { return p.mid >= 0; });
    if (L.length < 2 || R.length < 2) return { bins: bins, ok: false };
    var fl = wfit(L), fr = wfit(R);
    return { bins: bins, ok: true, fl: fl, fr: fr, gap: fr.a - fl.a };
  }

