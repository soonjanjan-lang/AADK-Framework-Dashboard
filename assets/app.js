  // ------------------------------------------------------------------ route: where am I
  function initRoute() {
    var links = Array.prototype.slice.call(document.querySelectorAll(".route__list a")), here = $("#route-here");
    var names = {}; links.forEach(function (a) { names[a.dataset.station] = a.querySelector(".route__name").textContent; });
    function mark(id) {
      links.forEach(function (a) { if (a.dataset.station === id) a.setAttribute("aria-current", "location"); else a.removeAttribute("aria-current"); });
      here.textContent = "You are at: " + names[id];
    }
    mark("question");
    if (!("IntersectionObserver" in window)) return;
    var vis = {};
    var io = new IntersectionObserver(function (entries) {
      entries.forEach(function (e) { vis[e.target.id] = e.isIntersecting ? e.intersectionRatio : 0; });
      var best = null, bv = 0;
      ["question", "plan", "data", "rdd", "combine", "framework"].forEach(function (id) { if ((vis[id] || 0) > bv) { bv = vis[id]; best = id; } });
      if (best) mark(best);
    }, { rootMargin: "-30% 0px -55% 0px", threshold: [0, 0.01, 0.2, 0.5, 1] });
    ["question", "plan", "data", "rdd", "combine", "framework"].forEach(function (id) { io.observe(document.getElementById(id)); });
  }

